"""
app/routers/drift_router.py
---------------------------------
GET /drift            — data-drift check vs. training baseline           [admin]
GET /drift/history     — daily mean confidence / detection rate, for a chart  [admin]
GET /drift/distribution — live vs. baseline confidence histogram              [admin]
"""
from fastapi import APIRouter, Depends, Query
from sqlalchemy.orm import Session

from app.core.security import CurrentUser, require_admin
from app.db.session import get_db
from app.services import drift_service

router = APIRouter(prefix="/drift", tags=["Monitoring"])


@router.get("")
def drift_check(db: Session = Depends(get_db), user: CurrentUser = Depends(require_admin)):
    """Compares recent /predict confidence scores to the training-time
    baseline (models/baseline_stats.json, generated by
    scripts/compute_baseline.py) to flag possible data drift."""
    return drift_service.check_drift(db)


@router.get("/history")
def drift_history(days: int = Query(30, ge=1, le=365), db: Session = Depends(get_db), user: CurrentUser = Depends(require_admin)):
    return drift_service.history(db, days=days)


@router.get("/distribution")
def drift_distribution(db: Session = Depends(get_db), user: CurrentUser = Depends(require_admin)):
    return drift_service.distribution(db)
